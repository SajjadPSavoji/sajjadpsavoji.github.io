/*
	Blog pages: shows the stories (generated by Prism, newest first) six at a time,
	with the theme's pagination bar under them. #page-3 opens a page, and a link to
	a story (#its-name) opens the page that holds it. Without JavaScript, every
	story shows on one page.
*/
(function() {

	var PER_PAGE = 6;

	var grid = document.querySelector('.blog-posts');
	if (!grid) return;
	var stories = Array.prototype.slice.call(grid.querySelectorAll(':scope > article'));
	var pages = Math.ceil(stories.length / PER_PAGE);
	if (pages < 2) return;

	var nav = document.createElement('ul');
	nav.className = 'pagination blog-pages';
	grid.parentNode.insertBefore(nav, grid.nextSibling);

	function item(html) {
		var li = document.createElement('li');
		li.innerHTML = html;
		nav.appendChild(li);
	}

	// First, last, and the pages next to the current one; gaps become an ellipsis.
	function numbers(page) {
		var out = [];
		for (var n = 1; n <= pages; n++)
			if (n == 1 || n == pages || Math.abs(n - page) <= 1) {
				if (out.length && n - out[out.length - 1] > 1) out.push(0);
				out.push(n);
			}
		return out;
	}

	function show(page) {
		page = Math.min(Math.max(page, 1), pages);

		// The grid's separators use :nth-child, so only the page's stories stay in it.
		grid.innerHTML = '';
		stories.slice((page - 1) * PER_PAGE, page * PER_PAGE).forEach(function(el) { grid.appendChild(el); });

		nav.innerHTML = '';
		item(page > 1 ? '<a href="#page-' + (page - 1) + '" class="button">Prev</a>' : '<span class="button disabled">Prev</span>');
		numbers(page).forEach(function(n) {
			item(n ? '<a href="#page-' + n + '" class="page' + (n == page ? ' active' : '') + '">' + n + '</a>' : '<span>&hellip;</span>');
		});
		item(page < pages ? '<a href="#page-' + (page + 1) + '" class="button">Next</a>' : '<span class="button disabled">Next</span>');
	}

	function open(scroll) {
		var id = decodeURIComponent(location.hash.slice(1)),
			m = /^page-(\d+)$/.exec(id),
			i = -1;
		for (var k = 0; k < stories.length; k++) if (stories[k].id && stories[k].id == id) i = k;

		if (i >= 0) {
			show(Math.floor(i / PER_PAGE) + 1);
			stories[i].scrollIntoView();
		} else {
			show(m ? +m[1] : 1);
			if (scroll) grid.parentNode.scrollIntoView();
		}
	}

	window.addEventListener('hashchange', function() { open(true); });
	open(false);

})();
